-- DEVICE ATTESTATIONS (challenge/response verification of new devices)
-- ----------------------------------------------------------------------------
CREATE TABLE device_attestations (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  target_device_id TEXT NOT NULL,
  challenger_device_id TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'challenged', 'attested', 'rejected')),
  challenge_data TEXT,                     -- JSON challenge (crypto material, not user content)
  proof_data TEXT,                         -- JSON proof
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  updated_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  UNIQUE (user_id, target_device_id, challenger_device_id)
);
CREATE INDEX idx_device_attestations_user ON device_attestations(user_id);
CREATE INDEX idx_device_attestations_target ON device_attestations(target_device_id);

-- ----------------------------------------------------------------------------
-- IDENTITY KEY LOG (append-only key transparency; no UPDATE/DELETE handlers)
-- ----------------------------------------------------------------------------
CREATE TABLE identity_key_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id TEXT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  device_id TEXT NOT NULL,
  commitment TEXT NOT NULL,
  identity_key_hash TEXT NOT NULL,
  previous_commitment TEXT,
  signature BLOB,                          -- Ed25519 over the commitment
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000))
);
CREATE INDEX idx_ik_log_user ON identity_key_log(user_id, created_at DESC);
CREATE INDEX idx_ik_log_device ON identity_key_log(user_id, device_id);
-- Prevent chain forks: one successor per commitment (NULL = first entry, also unique per user).
CREATE UNIQUE INDEX idx_ik_log_unique_prev
  ON identity_key_log(user_id, COALESCE(previous_commitment, '__NULL__'));

-- ----------------------------------------------------------------------------
-- E2EE RETRY REQUESTS (re-encryption requests for undecryptable messages)
-- ----------------------------------------------------------------------------
CREATE TABLE e2ee_retry_requests (
  id TEXT PRIMARY KEY,
  requester_user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  sender_user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message_id TEXT NOT NULL,
  message_type TEXT NOT NULL DEFAULT 'channel' CHECK (message_type IN ('channel', 'dm')),
  status TEXT NOT NULL DEFAULT 'pending',
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  UNIQUE (requester_user_id, message_id, message_type)
);
CREATE INDEX idx_e2ee_retry_requests_sender
  ON e2ee_retry_requests(sender_user_id, status)
  WHERE status = 'pending';

