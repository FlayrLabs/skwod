-- ----------------------------------------------------------------------------
-- E2EE KEY BACKUPS
-- ----------------------------------------------------------------------------
-- kdf_params carries the Argon2id parameters used at wrap time (JSON:
-- {"m_cost_kib":65536,"t_cost":3,"p_cost":1}) so parameter bumps never orphan
-- old backups. kdf is 'argon2id' for everything the new core writes.
CREATE TABLE e2ee_key_backups (
  user_id TEXT PRIMARY KEY REFERENCES profiles(id) ON DELETE CASCADE,
  encrypted_blob BLOB NOT NULL,
  salt BLOB NOT NULL,
  version INTEGER NOT NULL DEFAULT 1,
  kdf TEXT NOT NULL DEFAULT 'argon2id' CHECK (kdf IN ('argon2id')),
  kdf_params TEXT NOT NULL,
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  updated_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000))
);

-- ----------------------------------------------------------------------------
