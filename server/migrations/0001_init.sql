-- ----------------------------------------------------------------------------
-- CANVAS STATES (whiteboard; strokes are E2EE content)
-- ----------------------------------------------------------------------------
CREATE TABLE canvas_states (
  id TEXT PRIMARY KEY,
  channel_id TEXT NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  ciphertext BLOB NOT NULL,                -- encrypted strokes
  updated_by TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  updated_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  UNIQUE (channel_id)
);

-- ----------------------------------------------------------------------------
-- CHESS GAMES (board/history/clocks are E2EE content; seating is routing)
-- ----------------------------------------------------------------------------
CREATE TABLE chess_games (
  id TEXT PRIMARY KEY,
  channel_id TEXT NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  state_ciphertext BLOB NOT NULL,          -- FEN, move history, winner, clocks
  white_user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  black_user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'active', 'finished', 'abandoned')),
  last_move_at INTEGER,
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  updated_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  UNIQUE (channel_id)
);
