    /// A LiveKit that dies is brought back: the advertisement is withdrawn while it is down
    /// (its port is anyone's) and published again once the NEW child has proved it serves.
    #[tokio::test]
    async fn a_livekit_that_exits_is_restarted_with_backoff() {
        if !has_python() {
            eprintln!("skipped: python3 not available for the fake LiveKit");
            return;
        }
        let dir = tempfile::tempdir().unwrap();
        let st = state().await;
        // Each run serves for 4 s and exits; count the runs. Verifying a child takes at least
        // 1 s of that (the settle period in `child_serves`), more on a busy machine: a run that
        // lives only a little longer is advertised for an instant, or not at all.
        let runs = dir.path().join("runs");
        let body = format!("echo run >> {}\n{}", runs.display(), SERVE_OK.replace("SECS", "4"));
        let bin = script(dir.path(), &body);
        let backoff = (Duration::from_millis(300), Duration::from_millis(600));
        let managed = spawn_supervised(&st, dir.path(), &bin, Duration::from_secs(10), backoff).await;
        assert!(get(&st, "livekit_url").await.is_some());
        let count = || std::fs::read_to_string(&runs).map(|s| s.lines().count()).unwrap_or(0);
        assert_eq!(count(), 1);

        // It exits → withdrawn → restarted → advertised again; and again.
        // "Advertised again" is the URL together with the managed mark, seen in one look: the
        // child keeps exiting, so a second look taken later may land in the next gap.
        let mut saw_withdrawn = false;
        let cycled = async {
            loop {
                let up = get(&st, "livekit_url").await.is_some();
                saw_withdrawn |= !up;
                if saw_withdrawn && up && count() >= 3 && get(&st, "livekit_managed").await.as_deref() == Some("1") {
                    break;
                }
                tokio::time::sleep(Duration::from_millis(50)).await;
            }
        };
        tokio::time::timeout(Duration::from_secs(90), cycled).await.expect("LiveKit was restarted and advertised as managed again");
        assert!(saw_withdrawn, "never advertised while down");

        // Stopping hosting stops the restarts.
        managed.stop(&st).await;
        let n = count();
        tokio::time::sleep(Duration::from_millis(2500)).await;
        assert_eq!(count(), n, "no restart after stop");
        assert!(get(&st, "livekit_url").await.is_none());
    }
