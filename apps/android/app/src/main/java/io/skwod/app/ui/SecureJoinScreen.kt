/**
 * Host membership control for a space. Three ways in (security-first): one-time link (token),
 * reserved username, or a shareable code that files a request the host must approve. Below is the
 * live approval queue.
 */
@Composable
fun SecureJoinScreen(space: RealSpace, onClose: () -> Unit) {
    val ctx = LocalContext.current
    val model = AppModel.get(ctx)
    val scope = rememberCoroutineScope()
    var generated by remember { mutableStateOf<Pair<String, String>?>(null) } // kind, code
    var reserveName by remember { mutableStateOf("") }
    var status by remember { mutableStateOf<String?>(null) }
    var pending by remember { mutableStateOf<List<JoinRequest>>(emptyList()) }
    var tick by remember { mutableStateOf(0) }

    suspend fun refresh() {
        pending = try { model.client!!.listJoinRequests(space.serverId) } catch (_: Exception) { emptyList() }
    }
    LaunchedEffect(space.serverId, tick) { refresh() }

    // One-paste invite link: the skwod address + code, same <address>#<code> format as everywhere.
    // Carry the skwod's beacon (from this member's workspace) so a new member can find it again if the
    // address later moves. Android is never a host, so the fields only come from a member re-sharing.
    fun inviteLink(code: String): String {
        val w = model.current
        // A p2p skwod's invite is the host key + the code; nothing about a network address.
        // Shared as https://skwod.io/join#<key>.<code>: the fragment never reaches skwod.io.
        w?.nodeId?.let { node -> InviteLink.shareLink(node, code, w.fallbackUrl)?.let { return it } }
        return InviteBeacon.appended("${w?.server ?: ""}#$code", w?.beaconPubkey, w?.beaconContentKey)
    }

    fun mint(kind: String) = scope.launch {
        val code = withContext(Dispatchers.IO) {
            try {
                model.client!!.inviteToSpace(space.serverId, kind,
                    if (kind == "username") reserveName.trim().lowercase() else null)
            } catch (_: Exception) { null }
        }
        if (code != null) {
            generated = kind to code
            status = if (kind == "code") "Share this link. You'll approve each person below." else "Share this link — one paste, it includes the Skwod address."
        } else status = "Couldn't create the invite."
    }

    Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(20.dp)) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            IconButton(onClick = onClose) { Icon(Icons.Filled.ArrowBack, "Back", tint = Color.White) }
            Text("Invite to ${space.name}", color = Color.White, style = MaterialTheme.typography.titleLarge)
        }
        Spacer(Modifier.height(16.dp))

        // Invite tools. Channel keys are provisioned automatically over E2EE on approve, so there's
        // no separate "space key" to hand out — an invite is a single link.
        Card2 {
            Text("Create an invite", color = Color.White, fontWeight = FontWeight.SemiBold)
            Spacer(Modifier.height(8.dp))
            Button(onClick = { mint("token") }, modifier = Modifier.fillMaxWidth()) {
                Icon(Icons.Filled.Link, null); Spacer(Modifier.width(8.dp)); Text("One-time link (auto-join)")
            }
            Spacer(Modifier.height(8.dp))
            Row(verticalAlignment = Alignment.CenterVertically) {
                OutlinedTextField(reserveName, { reserveName = it }, label = { Text("reserve username") },
                    singleLine = true, modifier = Modifier.weight(1f))
                Spacer(Modifier.width(8.dp))
                OutlinedButton(onClick = { mint("username") }, enabled = reserveName.isNotBlank()) { Text("Reserve") }
            }
            Spacer(Modifier.height(8.dp))
            OutlinedButton(onClick = { mint("code") }, modifier = Modifier.fillMaxWidth()) {
                Icon(Icons.Filled.Numbers, null); Spacer(Modifier.width(8.dp)); Text("Shareable code (needs approval)")
            }
            generated?.let { (kind, code) ->
                Spacer(Modifier.height(8.dp))
                Text(when (kind) {
                    "token" -> "One-time invite link"; "username" -> "Reserved for @${reserveName.lowercase()}"
                    else -> "Shareable invite link (approval required)"
                }, color = Color.White.copy(alpha = 0.5f), style = MaterialTheme.typography.labelSmall)
                CopyRow(inviteLink(code), ctx)
            }
            status?.let { Text(it, color = SkAccent, style = MaterialTheme.typography.labelSmall) }
        }
        Spacer(Modifier.height(14.dp))

        // Approval queue.
        Card2 {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text("Pending requests", color = Color.White, fontWeight = FontWeight.SemiBold)
                Spacer(Modifier.weight(1f))
                IconButton(onClick = { tick++ }) { Icon(Icons.Filled.Refresh, "Refresh", tint = Color.White) }
            }
            if (pending.isEmpty()) {
                Text("No one waiting to join.", color = Color.White.copy(alpha = 0.45f),
                    style = MaterialTheme.typography.labelSmall)
            } else {
                pending.forEach { req ->
                    Row(Modifier.padding(vertical = 4.dp), verticalAlignment = Alignment.CenterVertically) {
                        // The name is the server's claim: shown through the contact book's rule…
                        val label = model.contacts.shown(req.userId, req.username).label
                        Monogram(req.username, size = 30); Spacer(Modifier.width(10.dp))
                        Text(label, color = Color.White, modifier = Modifier.weight(1f))
                        FilledIconButton(onClick = {
                            scope.launch {
                                // …and approved through the waiting room's "Let in": the name is
                                // checked again (look-alikes, unusual characters, the directory)
                                // before anything is signed or any key handed over.
                                model.waiting.letIn(WaitingMember(req.userId, req.username, WaitingMember.Source.REQUEST), space.serverId)
                                model.waiting.problem?.let { status = it }
                                tick++
                            }
                        }, colors = IconButtonDefaults.filledIconButtonColors(containerColor = Color(0xFF4ADE80))) {
                            Icon(Icons.Filled.Check, "Approve", tint = Color.Black)
                        }
                        Spacer(Modifier.width(6.dp))
                        OutlinedIconButton(onClick = {
                            scope.launch {
                                withContext(Dispatchers.IO) { try { model.client!!.denyJoinRequest(space.serverId, req.userId) } catch (_: Exception) {} }
                                tick++
                            }
                        }) { Icon(Icons.Filled.Close, "Deny", tint = Color(0xFFF87171)) }
                    }
                }
            }
        }
    }
}

@Composable
private fun Card2(content: @Composable ColumnScope.() -> Unit) {
    Surface(color = GlassCardTone, shape = RoundedCornerShape(16.dp), modifier = Modifier.fillMaxWidth()) {
        Column(Modifier.padding(16.dp), content = content)
    }
}

@Composable
private fun CopyRow(value: String, ctx: Context) {
    Row(Modifier.padding(vertical = 4.dp), verticalAlignment = Alignment.CenterVertically) {
        Text(value, color = Color.White, fontFamily = FontFamily.Monospace,
            style = MaterialTheme.typography.bodySmall, maxLines = 1, modifier = Modifier.weight(1f))
        // Native share — send the link straight to Messages/WhatsApp/etc. Also how a host re-shares
        // the CURRENT address after a move (the link always carries the live address).
        IconButton(onClick = {
            val send = android.content.Intent(android.content.Intent.ACTION_SEND).apply {
                type = "text/plain"; putExtra(android.content.Intent.EXTRA_TEXT, value)
            }
            ctx.startActivity(android.content.Intent.createChooser(send, "Share invite link"))
        }) { Icon(Icons.Filled.Share, "Share", tint = Color.White) }
        IconButton(onClick = {
            // An invite is a credential: flagged sensitive and cleared from the clipboard after 60 s.
            SecureClipboard.copy(ctx, value)
        }) { Icon(Icons.Filled.ContentCopy, "Copy", tint = Color.White) }
    }
}
