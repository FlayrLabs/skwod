-- ----------------------------------------------------------------------------
CREATE TABLE e2ee_backup_shares (
  id TEXT PRIMARY KEY,
  owner_user_id TEXT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  holder_user_id TEXT REFERENCES profiles(id) ON DELETE SET NULL,
  share_index INTEGER NOT NULL,
  share_ciphertext BLOB NOT NULL,
  threshold INTEGER NOT NULL,
  total_shares INTEGER NOT NULL,
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  UNIQUE (owner_user_id, share_index)
);
CREATE INDEX idx_backup_shares_owner ON e2ee_backup_shares(owner_user_id);
CREATE INDEX idx_backup_shares_holder ON e2ee_backup_shares(holder_user_id);

