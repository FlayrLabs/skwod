//! `skwod init` — one-command self-host bootstrap (ADR-008, installer/README.md).
//!
//! Steps mirror the mock: check Docker → LiveKit key/secret → start services (docker compose,
//! embedded bundle) → run migrations → print URL + admin join code. `--no-livekit` is the
//! Docker-less single-process path: no SFU, no compose; the operator runs `skwod run` directly.
//!
//! Secrets live only on the data volume: LiveKit creds in `<data>/config.toml`, and the admin
//! join code is printed once and stored only as a SHA-256 hash in `instance_secrets`
//! (`admin_setup_code`) for the Phase-8 first-signup gate to verify.

use rand::Rng;
use sha2::{Digest, Sha256};
use std::path::{Path, PathBuf};
use std::process::Command;

/// The deploy bundle, embedded so the binary stays self-contained.
const COMPOSE_YML: &str = include_str!("../../deploy/docker-compose.yml");

pub struct InitOptions {
    pub data: PathBuf,
    pub domain: String,
    pub no_livekit: bool,
    pub yes: bool,
    pub livekit_key: Option<String>,
    pub livekit_secret: Option<String>,
    pub database_url: Option<String>,
}

fn random_token(alphabet: &[u8], len: usize) -> String {
    let mut rng = rand::thread_rng();
    (0..len).map(|_| alphabet[rng.gen_range(0..alphabet.len())] as char).collect()
}

/// `SKWD-XXXX-XXXX` from an unambiguous alphabet (no 0/O/1/I).
pub fn generate_join_code() -> String {
    const ALPHABET: &[u8] = b"ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
    format!("SKWD-{}-{}", random_token(ALPHABET, 4), random_token(ALPHABET, 4))
}

pub(crate) fn generate_livekit_creds() -> (String, String) {
    const ALNUM: &[u8] = b"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
    (format!("lk_{}", random_token(ALNUM, 12)), random_token(ALNUM, 40))
}

fn mask(s: &str) -> String {
    if s.len() <= 8 {
        return "********".to_string();
    }
    format!("{}****...****{}", &s[..4], &s[s.len() - 4..])
}

fn docker_available() -> bool {
    let engine = Command::new("docker").arg("info").output().map(|o| o.status.success()).unwrap_or(false);
    let compose =
        Command::new("docker").args(["compose", "version"]).output().map(|o| o.status.success()).unwrap_or(false);
    engine && compose
}

fn docker_install_hint() -> &'static str {
    if cfg!(target_os = "macos") {
        "Install Docker Desktop: https://docs.docker.com/desktop/install/mac-install/"
    } else if cfg!(target_os = "linux") {
        "Install Docker Engine: https://docs.docker.com/engine/install/ (then `systemctl start docker`)"
    } else {
        "Install Docker: https://docs.docker.com/get-docker/"
    }
}

/// `uid:gid` of the invoking user (never root: a root `init` uses the image's own 1000:1000).
fn host_user() -> String {
    #[cfg(unix)]
    {
        let (uid, gid) = (nix::unistd::Uid::current().as_raw(), nix::unistd::Gid::current().as_raw());
        if uid != 0 && gid != 0 {
            return format!("{uid}:{gid}");
        }
    }
    "1000:1000".to_string()
}

/// `name@sha256:<64 hex>` — a reference that cannot be moved to other contents, unlike a tag.
pub(crate) fn image_is_pinned(image: Option<&str>) -> bool {
    image.and_then(|i| i.rsplit_once("@sha256:")).is_some_and(|(name, digest)| !name.is_empty() && digest.len() == 64 && digest.bytes().all(|b| b.is_ascii_hexdigit()))
}

fn write_config(data: &Path, domain: &str, livekit: Option<(&str, &str)>) -> std::io::Result<()> {
    let mut config = format!("# skwod instance config — generated by `skwod init`\ndomain = \"{domain}\"\n");
    if let Some((key, secret)) = livekit {
        config.push_str(&format!(
            "\n[livekit]\nurl = \"ws://localhost:7880\"\napi_key = \"{key}\"\napi_secret = \"{secret}\"\n"
        ));
    }
    std::fs::write(data.join("config.toml"), config)
}

/// Store only the code's hash; the plaintext is printed once and never persisted.
async fn store_admin_code_hash(pool: &crate::state::Db, code: &str) -> Result<(), sqlx::Error> {
    let hash = Sha256::digest(code.as_bytes()).to_vec();
    sqlx::query(
        "INSERT INTO instance_secrets (name, value, created_at) VALUES ('admin_setup_code', $1, $2)
         ON CONFLICT (name) DO UPDATE SET value = excluded.value, created_at = excluded.created_at",
    )
    .bind(hash)
    .bind(crate::state::now_ms())
    .execute(pool)
    .await?;
    Ok(())
}

/// Replace the (unclaimed) owner setup code with a fresh one and return it.
pub(crate) async fn rotate_setup_code(pool: &crate::state::Db) -> Result<String, sqlx::Error> {
    let code = generate_join_code();
    store_admin_code_hash(pool, &code).await?;
    Ok(code)
}

/// What `skwod run` found (or did) about bootstrap state. See [`ensure_initialized`].
#[derive(Debug, PartialEq, Eq)]
pub enum Bootstrap {
    /// `skwod init` (or an earlier auto-init) already ran: signup is join-code gated.
    Initialized,
    /// Fresh volume: an admin join code was just generated and stored (hash only). Print it once.
    AutoInitialized { join_code: String },
    /// Accounts exist but the instance was never initialized (a pre-existing open-signup
    /// deployment). Left untouched — locking it retroactively would hand ownership to whoever
    /// reads the log first — but it must be called out loudly.
    LegacyOpen,
    /// Open signup explicitly requested with `SKWOD_OPEN_SIGNUP=1` (dev / hosted-with-own-gate).
    OpenByChoice,
}

/// Make sure a freshly created instance is never left ownerless with open signup.
///
/// `skwod run` on an empty data volume (the Dockerfile `CMD`, or anyone skipping `skwod init`)
/// used to serve an instance where the first stranger to find it could sign up — and nobody
/// could ever become owner. Now `run` initializes it itself, exactly like `init` does.
pub async fn ensure_initialized(pool: &crate::state::Db) -> Result<Bootstrap, sqlx::Error> {
    let has_code: i64 = sqlx::query_scalar(
        "SELECT CAST(CASE WHEN EXISTS(SELECT 1 FROM instance_secrets WHERE name IN ('admin_setup_code', 'owner_user_id')) THEN 1 ELSE 0 END AS BIGINT)",
    )
    .fetch_one(pool)
    .await?;
    if has_code == 1 {
        return Ok(Bootstrap::Initialized);
    }
    let has_users: i64 =
        sqlx::query_scalar("SELECT CAST(CASE WHEN EXISTS(SELECT 1 FROM users) THEN 1 ELSE 0 END AS BIGINT)")
            .fetch_one(pool)
            .await?;
    if has_users == 1 {
        return Ok(Bootstrap::LegacyOpen);
    }
    if std::env::var("SKWOD_OPEN_SIGNUP").is_ok_and(|v| v == "1" || v.eq_ignore_ascii_case("true")) {
        return Ok(Bootstrap::OpenByChoice);
    }
    let join_code = generate_join_code();
    store_admin_code_hash(pool, &join_code).await?;
    Ok(Bootstrap::AutoInitialized { join_code })
}

pub async fn run_init(opts: InitOptions) -> Result<(), String> {
    println!("\nWelcome to skwod!\n");
    crate::ensure_data_dir(&opts.data).map_err(|e| format!("cannot create data dir: {e}"))?;

    // [1/4] Docker.
    if opts.no_livekit {
        println!("[1/4] Checking Docker... skipped (--no-livekit: single-process mode)");
    } else {
        print!("[1/4] Checking Docker... ");
        if docker_available() {
            println!("done");
        } else {
            println!("MISSING");
            return Err(format!(
                "Docker Engine + Compose are required for the default (LiveKit) profile.\n  {}\n  Or run text-only: skwod init --no-livekit",
                docker_install_hint()
            ));
        }
    }

    // [2/4] LiveKit credentials.
    let livekit = if opts.no_livekit {
        println!("[2/4] LiveKit setup... skipped (--no-livekit)");
        None
    } else {
        let (key, secret) = match (opts.livekit_key, opts.livekit_secret) {
            (Some(k), Some(s)) => (k, s),
            _ => generate_livekit_creds(),
        };
        println!("[2/4] LiveKit setup");
        println!("  → API Key: {}", mask(&key));
        println!("  → API Secret: ********");
        Some((key, secret))
    };
    write_config(&opts.data, &opts.domain, livekit.as_ref().map(|(k, s)| (k.as_str(), s.as_str())))
        .map_err(|e| format!("cannot write config.toml: {e}"))?;

    // [3/4] Services.
    match &livekit {
        Some(_) => {
            // The compose file names no image by itself: it runs exactly the image the host
            // pinned by digest (release audit M5), and `docker compose` would fail on the
            // missing variable with a message nobody can act on.
            let image = std::env::var("SKWOD_IMAGE").ok().filter(|i| !i.trim().is_empty());
            let Some(image) = image else {
                return Err("set SKWOD_IMAGE before running init: the skwod-server image pinned by digest (ghcr.io/flayrlabs/skwod-server@sha256:…), or the tag of an image you built yourself. docs/SELF-HOSTING.md says where the digest is published and how to verify its signature (deploy/verify-image.sh)".to_string());
            };
            if !image_is_pinned(Some(&image)) {
                println!("  ! SKWOD_IMAGE is a tag, not a digest. Fine for an image you built on this machine; a tag pulled from a registry is whatever the registry serves today.");
            }
            print!("[3/4] Starting services... ");
            let compose_path = opts.data.join("docker-compose.yml");
            std::fs::write(&compose_path, COMPOSE_YML).map_err(|e| format!("cannot write compose file: {e}"))?;
            let data_abs = std::fs::canonicalize(&opts.data).map_err(|e| format!("data dir: {e}"))?;
            let status = Command::new("docker")
                .args(["compose", "-f"])
                .arg(&compose_path)
                .args(["up", "-d"])
                .env("SKWOD_DATA", &data_abs)
                // The container runs as the user who ran `init`, so both can use the data dir.
                .env("SKWOD_RUN_AS", host_user())
                .status()
                .map_err(|e| format!("docker compose failed to start: {e}"))?;
            if !status.success() {
                return Err("docker compose up failed (see output above)".to_string());
            }
            println!("done");
        }
        None => {
            println!("[3/4] Starting services... skipped (single-process: run `skwod run --data {}`)", opts.data.display());
        }
    }

    // [4/4] Migrations (also generates the DB on a fresh volume).
    print!("[4/4] Running migrations... ");
    let pool = crate::open_db(&opts.data, opts.database_url.as_deref()).await.map_err(|e| format!("migrations failed: {e}"))?;
    println!("done");

    // Persist LiveKit creds into the DB so the voice-token endpoint can mint tokens (fail-closed
    // when absent — ADR-007).
    if let Some((key, secret)) = &livekit {
        for (name, value) in [("livekit_api_key", key.as_str()), ("livekit_api_secret", secret.as_str())] {
            sqlx::query(
                "INSERT INTO instance_secrets (name, value, created_at) VALUES ($1, $2, $3)
                 ON CONFLICT (name) DO UPDATE SET value = excluded.value, created_at = excluded.created_at",
            )
            .bind(name)
            .bind(value.as_bytes())
            .bind(crate::state::now_ms())
            .execute(&pool)
            .await
            .map_err(|e| format!("cannot store livekit creds: {e}"))?;
        }
    }

    let join_code = generate_join_code();
    store_admin_code_hash(&pool, &join_code).await.map_err(|e| format!("cannot store admin code: {e}"))?;

    let url = if opts.domain.starts_with("localhost") || opts.domain.contains(':') {
        format!("http://{}", opts.domain)
    } else {
        format!("https://{}", opts.domain)
    };
    println!("\n✓ Your instance is ready!\n");
    println!("URL: {url}");
    println!("Join code: {join_code}");
    // The p2p address is the instance's key (created here so the invite is complete on first print).
    match crate::p2p::node_id(&opts.data) {
        Ok(node) => println!("Invite: {}", crate::p2p::invite_link(node, Some(&join_code))),
        Err(e) => println!("(p2p invite unavailable: {e})"),
    }
    println!("\n(The join code is stored only as a hash — save it now.)");
    if opts.no_livekit {
        println!("Start the server with: skwod run --data {} --listen 0.0.0.0:3000", opts.data.display());
    }
    let _ = opts.yes; // reserved: future interactive prompts honor --yes
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn m5_only_a_digest_reference_counts_as_a_pinned_image() {
        let digest = "a".repeat(64);
        assert!(image_is_pinned(Some(&format!("ghcr.io/flayrlabs/skwod-server@sha256:{digest}"))));
        for loose in ["ghcr.io/flayrlabs/skwod-server:main", "skwod-server", "@sha256:abc", "x@sha256:zz", ""] {
            assert!(!image_is_pinned(Some(loose)), "{loose}");
        }
        assert!(!image_is_pinned(None));
    }

    #[test]
    fn join_code_shape() {
        for _ in 0..50 {
            let code = generate_join_code();
            assert_eq!(code.len(), 14);
            assert!(code.starts_with("SKWD-"));
            assert_eq!(code.as_bytes()[9], b'-');
            assert!(!code.contains('0') && !code.contains('O') && !code.contains('1') && !code.contains('I'));
        }
    }

    #[tokio::test]
    async fn run_without_init_never_leaves_a_fresh_instance_open() {
        use crate::tests::{send, test_app};
        use serde_json::json;
        let (app, db) = test_app().await;
        // Before: a never-initialized instance takes signups from anyone.
        assert!(!crate::join::signup_requires_code(&crate::state::AppState::new(db.clone(), std::env::temp_dir())).await.unwrap());

        // `skwod run` on a fresh volume initializes it.
        let Bootstrap::AutoInitialized { join_code } = ensure_initialized(&db).await.unwrap() else { panic!("fresh volume must auto-init") };
        let body = |code: Option<&str>| json!({ "username": "first", "password": "password123", "join_code": code });
        let (status, _) = send(&app, "POST", "/api/auth/signup", None, Some(body(None))).await;
        assert_eq!(status, axum::http::StatusCode::FORBIDDEN, "no code → no account");
        let (status, _) = send(&app, "POST", "/api/auth/signup", None, Some(body(Some("SKWD-AAAA-AAAA")))).await;
        assert_eq!(status, axum::http::StatusCode::FORBIDDEN, "wrong code → no account");
        let (status, _) = send(&app, "POST", "/api/auth/signup", None, Some(body(Some(&join_code)))).await;
        assert_eq!(status, axum::http::StatusCode::OK, "the printed code makes the first account (the owner)");

        // Idempotent afterwards: restarts neither mint a new code nor reopen signup.
        assert_eq!(ensure_initialized(&db).await.unwrap(), Bootstrap::Initialized);
    }

    #[tokio::test]
    async fn run_leaves_a_legacy_open_instance_alone() {
        let (app, db) = crate::tests::test_app().await;
        crate::tests::signup(&app, "oldtimer").await; // accounts exist, never initialized
        assert_eq!(ensure_initialized(&db).await.unwrap(), Bootstrap::LegacyOpen);
        assert_eq!(ensure_initialized(&db).await.unwrap(), Bootstrap::LegacyOpen, "and it does not get locked later");
    }

    #[test]
    fn masking_never_reveals_middle() {
        let (key, secret) = generate_livekit_creds();
        assert!(mask(&key).contains("****"));
        assert_eq!(mask("short"), "********");
        assert!(!mask(&secret).contains(&secret[5..30]));
    }
}
