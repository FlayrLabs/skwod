-- ============================================================================
-- skwod-native 0001_init — SQLite schema
-- ============================================================================
-- Ported from the original Postgres schema (skwod/supabase/migrations/
-- 00001_schema.sql, plus 00007_whiteboard.sql and 00008_chess.sql), with every
-- plaintext CONTENT column replaced by an opaque ciphertext BLOB.
--
-- E2EE invariant (docs/SECURITY.md, ADR-004): the server stores ONLY
-- ciphertext, public keys, and routing metadata. It can never read message
-- bodies, names people give things, attachments, or any other user content.
-- Columns named *_ciphertext (or `ciphertext`) are sealed client-side by
-- skwod-crypto; the server treats them as opaque bytes.
--
-- Supabase-specific machinery (RLS policies, triggers, functions, realtime
-- publication, storage buckets, auth.users) is intentionally NOT ported:
-- authorization lives in the server's Rust request handlers, and auth.users is
-- replaced by the local `users` table below.
--
-- Conventions:
--   ids           TEXT (UUID canonical string, generated by the application)
--   timestamps    INTEGER unix epoch milliseconds
--   booleans      INTEGER 0/1
--   permissions   INTEGER bitmask (same 15-permission semantics as original)
--   public keys / signatures / ciphertext   BLOB (raw bytes, not base64)
-- No PRAGMAs here: connection-level concerns (foreign_keys=ON, WAL) are set by
-- the server at connect time.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- USERS (new — replaces Supabase auth.users; the server does its own auth)
-- ----------------------------------------------------------------------------
-- Payment/entitlement is NOT a server concern: mobile is gated by App Store / Play
-- subscriptions (verified on-device via StoreKit / Play Billing), and the self-hosted
-- server only ever cares about invitation (join codes). So no billing columns here.
-- No email: skwod never sends mail (no verification/reset/notifications), so collecting
-- it only puts PII on a friend's self-hosted server for nothing. The username (in profiles,
-- UNIQUE) is the login identifier.
CREATE TABLE users (
  id TEXT PRIMARY KEY,
  password_hash TEXT NOT NULL,             -- Argon2id PHC string
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  updated_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000))
);

-- ----------------------------------------------------------------------------
-- PROFILES
-- ----------------------------------------------------------------------------
-- Original plaintext display_name / avatar_url / custom_status are gone; the
-- original's encrypted_name/bio/avatar columns become the only representation.
-- username stays plaintext: it is the routing/login identifier.
CREATE TABLE profiles (
  id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  username TEXT UNIQUE NOT NULL,
  status TEXT NOT NULL DEFAULT 'offline' CHECK (status IN ('online', 'idle', 'dnd', 'offline')),
  custom_status_ciphertext BLOB,
  name_ciphertext BLOB,
  bio_ciphertext BLOB,
  avatar_ciphertext BLOB,                  -- encrypted pointer/key for the avatar blob
  profile_key_version INTEGER NOT NULL DEFAULT 0,
  theme_mode TEXT CHECK (theme_mode IN ('light', 'dark', 'system')),
  glass_enabled INTEGER,
  accent_hue INTEGER CHECK (accent_hue IS NULL OR (accent_hue >= 0 AND accent_hue <= 360)),
  registration_pin_hash TEXT,
  registration_lock_enabled INTEGER NOT NULL DEFAULT 0,
  pin_attempt_count INTEGER NOT NULL DEFAULT 0,
  pin_locked_until INTEGER,
  last_seen_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  updated_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000))
);

-- ----------------------------------------------------------------------------
-- SERVERS
-- ----------------------------------------------------------------------------
CREATE TABLE servers (
  id TEXT PRIMARY KEY,
  name_ciphertext BLOB NOT NULL,
  description_ciphertext BLOB,
  icon_blob_id TEXT,                       -- opaque handle into the blob store
  owner_id TEXT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  updated_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000))
);

-- ----------------------------------------------------------------------------
-- ROLES (permissions bitmask semantics preserved from the original)
-- ----------------------------------------------------------------------------
CREATE TABLE roles (
  id TEXT PRIMARY KEY,
  server_id TEXT NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  name_ciphertext BLOB NOT NULL,
  color TEXT CHECK (color IS NULL OR (length(color) = 7 AND substr(color, 1, 1) = '#')),
  permissions INTEGER NOT NULL DEFAULT 0,
  position INTEGER NOT NULL DEFAULT 0,
  is_default INTEGER NOT NULL DEFAULT 0,
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  updated_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000))
);
CREATE INDEX idx_roles_server ON roles(server_id);

-- ----------------------------------------------------------------------------
-- SERVER MEMBERS
-- ----------------------------------------------------------------------------
CREATE TABLE server_members (
