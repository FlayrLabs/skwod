-- ----------------------------------------------------------------------------
-- MESSAGES
-- ----------------------------------------------------------------------------
-- Original content / sealed_content / encryption_metadata collapse into one
-- opaque envelope. search_vector is gone: search is client-side over the local
-- encrypted cache. mention_user_ids stays as routing metadata so the server
-- can fan out mention pushes / unread counts (same tradeoff as the original).
CREATE TABLE messages (
  id TEXT PRIMARY KEY,
  channel_id TEXT NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  author_id TEXT REFERENCES profiles(id) ON DELETE CASCADE,
  author_device_id TEXT,
  ciphertext BLOB NOT NULL,                -- sealed-sender envelope (sender key message inside)
  is_edited INTEGER NOT NULL DEFAULT 0,
  is_pinned INTEGER NOT NULL DEFAULT 0,
  reply_to_id TEXT REFERENCES messages(id) ON DELETE SET NULL,
  deleted_at INTEGER,
  mention_user_ids TEXT,                   -- JSON array of user ids (routing metadata)
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  updated_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000))
);
CREATE INDEX idx_messages_channel ON messages(channel_id, created_at DESC);
CREATE INDEX idx_messages_author ON messages(author_id);

-- ----------------------------------------------------------------------------
-- MESSAGE ATTACHMENTS
-- ----------------------------------------------------------------------------
-- file_name / mime_type / dimensions / duration / spoiler flag move inside
-- metadata_ciphertext. The server keeps only what it must: the opaque blob
-- location and its size (which it can observe anyway).
CREATE TABLE message_attachments (
  id TEXT PRIMARY KEY,
  message_id TEXT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  storage_path TEXT NOT NULL,              -- opaque path under <data>/blobs
  file_size INTEGER NOT NULL,
  metadata_ciphertext BLOB NOT NULL,       -- name, mime, dimensions, duration, spoiler, content key
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000))
);
CREATE INDEX idx_message_attachments_message ON message_attachments(message_id);

-- ----------------------------------------------------------------------------
-- MESSAGE LINK PREVIEWS (client-generated + encrypted; server never fetches URLs)
-- ----------------------------------------------------------------------------
CREATE TABLE message_link_previews (
  id TEXT PRIMARY KEY,
  message_id TEXT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  ciphertext BLOB NOT NULL,                -- url, title, description, image, site name
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000))
);
CREATE INDEX idx_message_link_previews_message ON message_link_previews(message_id);

-- ----------------------------------------------------------------------------
-- REACTIONS
-- ----------------------------------------------------------------------------
-- The emoji itself is content. emoji_hash is a client-computed keyed hash
-- (deterministic per channel key) so the server can enforce one-reaction-per-
-- emoji uniqueness without learning which emoji it is.
CREATE TABLE reactions (
  id TEXT PRIMARY KEY,
  message_id TEXT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  emoji_hash TEXT NOT NULL,
  emoji_ciphertext BLOB NOT NULL,
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  UNIQUE (message_id, user_id, emoji_hash)
);
CREATE INDEX idx_reactions_message ON reactions(message_id);

