#[cfg(all(test, unix))]
mod spawn_tests {
    use super::*;
    use std::time::Duration;

    async fn state() -> AppState {
        let (_app, db) = crate::tests::test_app().await;
        AppState::new(db, std::env::temp_dir())
    }

    fn script(dir: &Path, body: &str) -> PathBuf {
        use std::os::unix::fs::PermissionsExt;
        let path = dir.join("fake-livekit");
        std::fs::write(&path, format!("#!/bin/sh\n{body}\n")).unwrap();
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755)).unwrap();
        path
    }

    /// A fake LiveKit that really listens on the configured port and answers `OK`, for `secs`.
    const SERVE_OK: &str = r#"port=$(grep '^port:' "$2" | cut -d' ' -f2)
exec python3 -c "
import http.server, sys, threading
class H(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        self.send_response(200); self.send_header('content-length', '2'); self.end_headers(); self.wfile.write(b'OK')
    def log_message(self, *a): pass
s = http.server.HTTPServer(('127.0.0.1', int(sys.argv[1])), H)
threading.Timer(float(sys.argv[2]), s.shutdown).start()
s.serve_forever()
" "$port" SECS"#;

    fn has_python() -> bool {
        std::process::Command::new("python3").arg("--version").output().is_ok_and(|o| o.status.success())
    }

    #[tokio::test]
    async fn nothing_is_advertised_when_the_child_dies_or_never_listens() {
        let dir = tempfile::tempdir().unwrap();
        let st = state().await;
        // Dies at once (what LiveKit does when a port is taken).
        assert!(spawn_with(&st, dir.path(), &script(dir.path(), "exit 1"), Duration::from_secs(2)).await.is_none());
        assert_eq!(get(&st, "livekit_url").await, None);
        // Alive but not listening.
        assert!(spawn_with(&st, dir.path(), &script(dir.path(), "sleep 30"), Duration::from_millis(800)).await.is_none());
        assert_eq!(get(&st, "livekit_url").await, None);
        assert_eq!(get(&st, "livekit_managed").await, None);
    }

    #[tokio::test]
    async fn a_port_squatter_is_never_advertised() {
        // Another local process already owns the remembered signaling port and even answers like
        // LiveKit. Our child cannot bind it and exits → that port must not be published; the retry
        // on fresh ports fails too (the fake always exits), so voice simply stays off.
        let squatter = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let port = squatter.local_addr().unwrap().port();
        tokio::spawn(async move {
            use tokio::io::{AsyncReadExt, AsyncWriteExt};
            while let Ok((mut s, _)) = squatter.accept().await {
                let mut buf = [0u8; 1024];
                let _ = s.read(&mut buf).await;
                let _ = s.write_all(b"HTTP/1.1 200 OK\r\ncontent-length: 2\r\n\r\nOK").await;
            }
        });
        let dir = tempfile::tempdir().unwrap();
        let st = state().await;
        put(&st, "livekit_signal_port", &port.to_string()).await.unwrap();
        put(&st, "livekit_udp_port", "50999").await.unwrap();
        // Worst case for the old check: the child is ALIVE (still starting) while the squatter answers.
        assert!(spawn_with(&st, dir.path(), &script(dir.path(), "sleep 30"), Duration::from_millis(1500)).await.is_none());
        assert_eq!(get(&st, "livekit_url").await, None, "the squatted port was never advertised");
        // And when the squatter shows up only AFTER the pre-spawn check, the listener-pid check
        // (where lsof exists) still refuses it.
        if listener_pids(port).await.is_some() {
            let mut alive = tokio::process::Command::new("sleep").arg("30").kill_on_drop(true).spawn().unwrap();
            let addr = std::net::SocketAddr::from(([127, 0, 0, 1], port));
            assert!(!child_serves(&mut alive, addr, Duration::from_secs(2)).await, "an alive child that isn't the listener is not accepted");
        }
    }

    #[tokio::test]
    async fn stale_advertisement_is_withdrawn_before_anything_else() {
        let dir = tempfile::tempdir().unwrap();
        let st = state().await;
        // A previous run left a managed URL behind; this run has no LiveKit binary to verify with.
        put(&st, "livekit_url", "ws://127.0.0.1:7880").await.unwrap();
        put(&st, "livekit_managed", "1").await.unwrap();
        std::env::set_var("SKWOD_LIVEKIT_BIN", dir.path().join("does-not-exist"));
        assert!(spawn_managed(&st, dir.path()).await.is_none());
        std::env::remove_var("SKWOD_LIVEKIT_BIN");
        assert_eq!(get(&st, "livekit_url").await, None);
        // An owner-configured external SFU is never touched.
        put(&st, "livekit_url", "wss://sfu.example.org").await.unwrap();
        assert!(spawn_managed(&st, dir.path()).await.is_none());
        assert_eq!(get(&st, "livekit_url").await.as_deref(), Some("wss://sfu.example.org"));
    }

    #[tokio::test]
    async fn advertised_only_while_our_child_serves_and_withdrawn_when_it_exits() {
        if !has_python() {
            eprintln!("skipped: python3 not available for the fake LiveKit");
            return;
        }
        let dir = tempfile::tempdir().unwrap();
        let st = state().await;
        let bin = script(dir.path(), &SERVE_OK.replace("SECS", "2.5"));
        let managed = spawn_with(&st, dir.path(), &bin, Duration::from_secs(10)).await.expect("verified child");
        let url = get(&st, "livekit_url").await.expect("advertised after verification");
        let port = get(&st, "livekit_signal_port").await.unwrap();
        assert_eq!(url, format!("ws://127.0.0.1:{port}"));
        assert_eq!(get(&st, "livekit_managed").await.as_deref(), Some("1"));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(dir.path().join("livekit.yaml")).unwrap().permissions().mode();
            assert_eq!(mode & 0o777, 0o600, "the config holds the API secret");
        }
        // The child exits on its own → the advertisement goes away without a restart.
        let gone = async {
            while get(&st, "livekit_url").await.is_some() {
                tokio::time::sleep(Duration::from_millis(100)).await;
            }
        };
        tokio::time::timeout(Duration::from_secs(10), gone).await.expect("withdrawn after the child exits");
        drop(managed);
    }

    /// A LiveKit that dies is brought back: the advertisement is withdrawn while it is down
    /// (its port is anyone's) and published again once the NEW child has proved it serves.
    #[tokio::test]
    async fn a_livekit_that_exits_is_restarted_with_backoff() {
        if !has_python() {
            eprintln!("skipped: python3 not available for the fake LiveKit");
            return;
        }
        let dir = tempfile::tempdir().unwrap();
        let st = state().await;
        // Each run serves for 4 s and exits; count the runs. Verifying a child takes at least
        // 1 s of that (the settle period in `child_serves`), more on a busy machine: a run that
        // lives only a little longer is advertised for an instant, or not at all.
        let runs = dir.path().join("runs");
        let body = format!("echo run >> {}\n{}", runs.display(), SERVE_OK.replace("SECS", "4"));
        let bin = script(dir.path(), &body);
        let backoff = (Duration::from_millis(300), Duration::from_millis(600));
        let managed = spawn_supervised(&st, dir.path(), &bin, Duration::from_secs(10), backoff).await.expect("verified child");
        assert!(get(&st, "livekit_url").await.is_some());
        let count = || std::fs::read_to_string(&runs).map(|s| s.lines().count()).unwrap_or(0);
        assert_eq!(count(), 1);

        // It exits → withdrawn → restarted → advertised again; and again.
        // "Advertised again" is the URL together with the managed mark, seen in one look: the
        // child keeps exiting, so a second look taken later may land in the next gap.
        let mut saw_withdrawn = false;
        let cycled = async {
            loop {
                let up = get(&st, "livekit_url").await.is_some();
                saw_withdrawn |= !up;
                if saw_withdrawn && up && count() >= 3 && get(&st, "livekit_managed").await.as_deref() == Some("1") {
                    break;
                }
                tokio::time::sleep(Duration::from_millis(50)).await;
            }
        };
        tokio::time::timeout(Duration::from_secs(90), cycled).await.expect("LiveKit was restarted and advertised as managed again");
        assert!(saw_withdrawn, "never advertised while down");

        // Stopping hosting stops the restarts.
        managed.stop(&st).await;
        let n = count();
        tokio::time::sleep(Duration::from_millis(2500)).await;
        assert_eq!(count(), n, "no restart after stop");
        assert!(get(&st, "livekit_url").await.is_none());
    }
}
