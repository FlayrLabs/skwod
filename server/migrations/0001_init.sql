-- ----------------------------------------------------------------------------
-- USER DEVICES
-- ----------------------------------------------------------------------------
-- Matches skwod-crypto's identity model (x3dh.rs): identity = X25519 DH public
-- + Ed25519 signing public (the original had a single identity_key column).
-- pq_spk_* are the ML-KEM-1024 signed prekey (PQXDH); NULL marks a
-- classical-only legacy device (PQ-capable initiators refuse these, ADR-006).
CREATE TABLE user_devices (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  device_id TEXT NOT NULL,
  device_name_ciphertext BLOB,
  identity_dh_public BLOB NOT NULL,        -- X25519
  identity_signing_public BLOB NOT NULL,   -- Ed25519
  spk_public BLOB NOT NULL,                -- X25519 signed prekey
  spk_sig BLOB NOT NULL,                   -- Ed25519(spk_public)
  pq_spk_public BLOB,                      -- ML-KEM-1024 signed prekey
  pq_spk_sig BLOB,                         -- Ed25519(pq_spk_public)
  spk_timestamp INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  attested INTEGER NOT NULL DEFAULT 0,
  created_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  last_active_at INTEGER NOT NULL DEFAULT ((strftime('%s','now') * 1000)),
  UNIQUE (user_id, device_id)
);
CREATE INDEX idx_user_devices_user ON user_devices(user_id);

